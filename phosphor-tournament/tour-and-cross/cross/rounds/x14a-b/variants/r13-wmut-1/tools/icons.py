def rows(name):
    r = [line for line in G[name].strip("\n").split("\n")]
    assert len(r) == 12, (name, len(r))
    for line in r:
        assert len(line) == 12, (name, line, len(line))
    return r


def solid(name):
    out = []
    for y, line in enumerate(rows(name)):
        x = 0
        while x < 12:
            if line[x] == "#":
                start = x
                while x < 12 and line[x] == "#":
                    x += 1
                out.append(f'<rect x="{start*2}" y="{y*2}" width="{(x-start)*2}" height="2"/>')
            else:
                x += 1
    return "".join(out)


def separated(name):
    out = []
    for y, line in enumerate(rows(name)):
        for x, c in enumerate(line):
            if c == "#":
                out.append(f'<rect x="{x*2+0.25}" y="{y*2+0.25}" width="1.5" height="1.5"/>')
    return "".join(out)


def main():
    names = sorted(G)
    print('<!-- Mosaic icons for FamilyDB, drawn on a 12 x 12 grid of videotex blocks. i-* solid, m-* separated. -->')
    print('<svg xmlns="http://www.w3.org/2000/svg" fill="currentColor" stroke="none">')
    for n in names:
        print(f'<symbol id="i-{n}" viewBox="0 0 24 24"><g fill="currentColor" stroke="none" shape-rendering="crispEdges">{solid(n)}</g></symbol>')
    for n in names:
        print(f'<symbol id="m-{n}" viewBox="0 0 24 24"><g fill="currentColor" stroke="none">{separated(n)}</g></symbol>')
    print("</svg>")


if __name__ == "__main__":
    main()
