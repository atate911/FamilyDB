TONES = (("#", ""), ("o", ' opacity=".55"'), ("+", ' opacity=".2"'))


def path(art, ch="#"):
    rows = [r for r in art.strip("\n").split("\n")]
    n = len(rows)
    assert n in (9, 18), art
    d = []
    for y, row in enumerate(rows):
        assert len(row) == n, (row, art)
        x = 0
        while x < n:
            if row[x] == ch:
                s = x
                while x < n and row[x] == ch:
                    x += 1
                d.append(f"M{s} {y}h{x-s}v1h-{x-s}z")
            else:
                x += 1
    return "".join(d)


def symbol(name, art):
    n = len(art.strip("\n").split("\n"))
    paths = "".join(f'<path fill="currentColor"{extra} shape-rendering="crispEdges" d="{path(art, ch)}"/>'
                    for ch, extra in TONES if ch in art)
    return f'<symbol id="i-{name}" viewBox="0 0 {n} {n}">{paths}</symbol>'


out = ['<!-- Pocket Timeline, Instruments: pixel sprites on a 9x9 grid, the mark on 18x18 (the pocket instrument, smiling), drawn for FamilyDB (one pixel = one unit). -->',
       '<svg xmlns="http://www.w3.org/2000/svg">']
for name, art in ART.items():
    out.append(symbol(name, art))
out.append("</svg>")
Path(__file__).resolve().parent.joinpath("static", "icons.svg").write_text("\n".join(out) + "\n")
print(len(ART), "icons")
